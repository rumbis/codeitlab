// @effect-diagnostics nodeBuiltinImport:off - the guard reads the repository from disk.
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

import { describe, expect, it } from "vite-plus/test";

/**
 * The product is CodeItLab everywhere: names, ids, paths, origins and prose.
 * No shipped or tracked file may still name the retired upstream brand, so this
 * guard walks the checkout instead of a hand-picked list of directories. It is
 * the only place that can catch a rename that missed one surface.
 */
const ROOT = NodePath.resolve(new URL("../../../../../", import.meta.url).pathname);

// Assembled so this file does not contain the token it forbids.
const RETIRED = new RegExp(`(^|[^A-Za-z0-9_])t${3}([^A-Za-z0-9_]|$)`, "i");

const SKIPPED_DIRECTORIES = new Set([
  ".cil",
  ".generated",
  ".git",
  ".next",
  ".repos",
  ".turbo",
  "Pods",
  "android",
  "build",
  "coverage",
  "ios",
  "node_modules",
  "out",
  "release",
]);

/** `dist`, `dist-electron`, `dist-exe` and friends are build output. */
const SKIPPED_DIRECTORY_PREFIXES = ["dist"];

/**
 * Vendored binaries, archives and screenshots hold the token in compressed or
 * generated bytes that cannot be edited without corrupting them.
 */
const SKIPPED_EXTENSIONS = new Set([
  ".a",
  ".bin",
  ".class",
  ".db",
  ".dmg",
  ".dylib",
  ".gif",
  ".gz",
  ".icns",
  ".ico",
  ".jar",
  ".jpeg",
  ".jpg",
  ".mov",
  ".mp3",
  ".mp4",
  ".node",
  ".o",
  ".otf",
  ".pdf",
  ".png",
  ".rlib",
  ".so",
  ".sqlite",
  ".tgz",
  ".ttf",
  ".wasm",
  ".webm",
  ".webp",
  ".woff",
  ".woff2",
  ".zip",
]);

const isText = (file: string): boolean => {
  if (SKIPPED_EXTENSIONS.has(NodePath.extname(file).toLowerCase())) return false;
  return !NodeFS.readFileSync(file).includes(0);
};

const walk = (directory: string, files: Array<string>): Array<string> => {
  for (const entry of NodeFS.readdirSync(directory, { withFileTypes: true })) {
    const full = NodePath.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (SKIPPED_DIRECTORIES.has(entry.name)) continue;
      if (SKIPPED_DIRECTORY_PREFIXES.some((prefix) => entry.name.startsWith(prefix))) continue;
      walk(full, files);
    } else if (entry.isFile() && isText(full)) {
      files.push(full);
    }
  }
  return files;
};

const offenders = (files: Array<string>): Array<string> =>
  files.flatMap((file) =>
    NodeFS.readFileSync(file, "utf8")
      .split("\n")
      .flatMap((line, index) =>
        RETIRED.test(line)
          ? [`${NodePath.relative(ROOT, file)}:${index + 1}: ${line.trim().slice(0, 160)}`]
          : [],
      ),
  );

describe("retired brand drift", () => {
  it("leaves no tracked file naming the retired upstream brand", () => {
    const files = walk(ROOT, []);
    expect(files.length).toBeGreaterThan(1_000);
    expect(offenders(files)).toEqual([]);
  });

  it("keeps retired brand out of repository paths", () => {
    const paths = walk(ROOT, []).map((file) => NodePath.relative(ROOT, file));
    expect(paths.filter((path) => RETIRED.test(path))).toEqual([]);
  });
});
